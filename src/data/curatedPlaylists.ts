export function getHubZoneForSlug(slug: string): HubZone | undefined {
  if (SONGBOOK_HUB_SLUGS.has(slug)) return 'songbook'
  if (ISRAELI_HUB_SLUGS.has(slug)) return 'israeli'
  if (INTERNATIONAL_ARTIST_SLUGS.has(slug)) return 'international'
  // International hub = genre shelves (decades / difficulty stay separate rows).
  if (curatedPlaylistSectionBySlug[slug] === 'genre') return 'international'
  // Fallback: Top * chart shelves always belong to a hub zone.
  if (slug === 'spotify-top-france' || slug === 'spotify-top-global') {
    return 'international'
  }
  if (slug === 'spotify-top-israel') return 'israeli'
  return undefined
}

/** French artist / chart / genre shelves (subset of the international hub). */
export function isFrenchCatalogSlug(slug: string): boolean {
  if (INTERNATIONAL_ARTIST_SLUGS.has(slug)) return true
  if (slug === 'spotify-top-france') return true
  if (slug.startsWith('french-')) return true
  return false
}
